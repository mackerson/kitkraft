def feasible(c):
    """Signatures a transcription can turn into typed members: the opaque members, and for an
    lstring-only definition (which names only EDID and the lstrings) its unknowns too, less
    the ones that live in component bodies. A full or inventory definition already names every
    top-level signature, so its unknowns are component-body subrecords (raw by design). Opaque
    members the definition keeps raw on purpose (a note saying "kept raw", or VMAD) and
    unknown VMAD do not count."""
    raw = len(c["def"]["raw"])
    if c["def"]["kind"] != "lstring-only":
        return max(0, c["opaque"] - raw)
    body = sum(1 for s, _ in c["outside"] if s in BODY_SIGS or s in RAW_SIGS)
    return max(0, c["opaque"] - raw) + max(0, c["unknown"] - body)


def depth_target(c):
    """(typed at least, unknown at most): half the feasible signatures typed, none added unknown."""
    return c["typed"] + max(1, math.ceil(feasible(c) / 2)), c["unknown"]


def variant_users(sig):
    """Hand-written Rust files that name the generated record variant (`Typed::Stat`)."""
    variant = sig.replace("_", "").capitalize()
    pat = re.compile(r"\b(?:Typed|TypedRecord|Generated)::" + variant + r"\b")
    hits = []
    for base in ("crates", "apps"):
        for p in glob.glob(os.path.join(ROOT, base, "**", "*.rs"), recursive=True):
            rel = os.path.relpath(p, ROOT).replace(os.sep, "/")
            if "/generated/" in rel or "/target/" in rel:
                continue
            try:
                if pat.search(open(p, encoding="utf-8", errors="replace").read()):
                    hits.append(rel)
            except OSError:
                pass
    return sorted(hits)


