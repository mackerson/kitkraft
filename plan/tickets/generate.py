def comma(n):
    return f"{n:,}"


def parity_rows():
    """{SIG: row dict} from the "## Record types" table of docs/record-parity.md."""
    text = open(PARITY, encoding="utf-8").read()
    part = text.split("## Record types", 1)[1].split("\n## ", 1)[0]
    rows = {}
    for line in part.splitlines():
        m = re.match(r"^\| `(.{4})` +\|(.*)\|$", line)
        if not m:
            continue
        cells = [c.strip().replace(",", "") for c in m.group(2).split("|")]
        schema, records, compressed, seen, typed, opaque, unknown = cells
        rows[m.group(1)] = dict(sig=m.group(1), schema=schema, records=int(records),
                                compressed=int(compressed), seen=int(seen), typed=int(typed),
                                opaque=int(opaque), unknown=int(unknown))
    if not rows:
        sys.exit(f"no record rows found in {PARITY}")
    return rows


def parity_outside():
    """{SIG: [(sub, occurrences)]}: "## Subrecords outside the definitions" (defined types)."""
    text = open(PARITY, encoding="utf-8").read()
    if "## Subrecords outside the definitions" not in text:
        return {}
    part = text.split("## Subrecords outside the definitions", 1)[1].split("\n## ", 1)[0]
    out = {}
    for m in re.finditer(r"^- `(.{4})`: (.*)$", part, re.M):
        out[m.group(1)] = [(s, int(n.replace(",", ""))) for s, n in re.findall(r"`(.{4})` \(([\d,]+)\)", m.group(2))]
    return out


# Signatures that, where a full definition leaves them unnamed, occur only inside base form
# component bodies (BFCB..BFCE, kept raw): REFR's note in docs/record-parity.md and the
# unknowns of the typed definitions (STAT, LIGH, COBJ, FLST, LCRT, NPC_, MSTT, KYWD).
BODY_SIGS = {"FLTR", "INTV", "VLMS", "OPDS", "FLCS", "SODA", "WAIM", "WFIR"}
# Payloads every definition keeps raw on purpose (script data: unions by property type).
RAW_SIGS = {"VMAD"}


def definitions():
    """{SIG: {name, kind, text}} for crates/schema/defs/<SIG>.toml (record types only)."""
    out = {}
    for p in sorted(glob.glob(os.path.join(DEFS, "*.toml"))):
        sig = os.path.basename(p)[:-5]
        if sig in HEADER_DEFS:
            continue
        text = open(p, encoding="utf-8").read()
        m = re.search(r'^name = "([^"]+)"', text, re.M)
        note = re.search(r'^note = "([^"]*)"', text, re.M)
        note = note.group(1) if note else ""
        kind = ("lstring-only" if "lstring-only" in note else
                "inventory" if "inventory definition" in note else "typed")
        raw = set()
        for block in re.split(r"\n(?=\[\[)", text):
            sub = re.search(r'^sig = "(.{4})"', block, re.M)
            note_m = re.search(r'^note = "([^"]*)"', block, re.M)
            if sub and re.search(r'^type = "opaque"', block, re.M) and (
                    sub.group(1) in RAW_SIGS or (note_m and "kept raw" in note_m.group(1))):
                raw.add(sub.group(1))
        out[sig] = dict(name=m.group(1) if m else sig, kind=kind, text=text, raw=sorted(raw),
                        components=("BfcbBlock" in text or "any_until" in text))
    return out


def type_names():
    """Every type name the schema and the generated code already use (collisions to avoid)."""
    names = set()
    for p in glob.glob(os.path.join(DEFS, "**", "*.toml"), recursive=True):
        names |= set(re.findall(r'^name = "([^"]+)"', open(p, encoding="utf-8").read(), re.M))
    gen = os.path.join(ROOT, "crates", "esm", "src", "generated", "records.rs")
    if os.path.exists(gen):
        names |= set(re.findall(r"\bpub (?:struct|enum|type) (\w+)", open(gen, encoding="utf-8").read()))
    codegen = os.path.join(ROOT, "crates", "schema", "src", "codegen.rs")
    if os.path.exists(codegen):
        block = re.search(r"RESERVED_TYPE_NAMES: &\[&str\] = &\[(.*?)\];", open(codegen, encoding="utf-8").read(), re.S)
        if block:
            names |= set(re.findall(r'"(\w+)"', block.group(1)))
    return names


def families():
    """{SIG: family} from xtask/src/parity.rs FAMILIES (other types: container/other)."""
    src = open(os.path.join(ROOT, "xtask", "src", "parity.rs"), encoding="utf-8").read()
    block = re.search(r"const FAMILIES: &\[\(&str, &\[&str\]\)\] = &\[(.*?)\n\];", src, re.S)
    out = {}
    if block:
        for fam, body in re.findall(r'\(\s*"([\w/]+)",\s*&\[(.*?)\]', block.group(1), re.S):
            for sig in re.findall(r'"(.{4})"', body):
                out[sig] = fam
    return out


def merged_ids():
    """Tickets merged to main: a "Merge ticket/<ID>:" commit, or `merged` in the README table."""
    ids = set()
    r = subprocess.run(["git", "-C", ROOT, "log", "--format=%s", "main"], capture_output=True, text=True)
    ids |= set(re.findall(r"^Merge ticket/(KK-\d+):", r.stdout, re.M))
    for line in open(README, encoding="utf-8"):
        m = re.match(r"^\| \[(KK-\d+)\]\(KK-\d+\.toml\) \|.*\| merged", line)
        if m:
            ids.add(m.group(1))
    return ids


def load_tickets():
    """[(path, ticket dict, is_draft)] for plan/tickets/KK-*.toml and drafts/*.toml."""
    out = []
    for p in sorted(glob.glob(os.path.join(TICKETS, "KK-*.toml"))):
        out.append((p, tomllib.load(open(p, "rb")), False))
    for p in sorted(glob.glob(os.path.join(TICKETS, "drafts", "*.toml"))):
        try:
            out.append((p, tomllib.load(open(p, "rb")), True))
        except tomllib.TOMLDecodeError as e:
            print(f"warning: {p}: {e}; skipped", file=sys.stderr)
    return out


def coverage(tickets, merged, sigs):
    """{SIG: [why]} for each type a ticket or draft already covers.

    `owned`: a ticket or draft owns crates/schema/defs/<SIG>.toml, merged or not
    (`open_owned`: unmerged ones and drafts). `mentioned`: an unmerged ticket or a draft
    names the type as a word in its title or brief, or a draft's file name does
    (type-avif.toml); `titled`: the same, title and draft file name only. Inventory skips
    owned or mentioned types (a brief that names an undefined type is about it); depth skips
    types an open ticket owns or titles (briefs name typed types as examples).
    """
    owned, open_owned, mentioned, titled = {}, {}, {}, {}
    for path, t, draft in tickets:
        tid = os.path.basename(path)[:-5] if draft else t.get("id", os.path.basename(path)[:-5])
        label = f"draft {os.path.basename(path)}" if draft else tid
        is_open = draft or tid not in merged
        for o in t.get("owns", []):
            m = re.fullmatch(r"crates/schema/defs/([A-Z0-9_]{4})\.toml", o)
            if m:
                owned.setdefault(m.group(1), []).append(label)
                if is_open:
                    open_owned.setdefault(m.group(1), []).append(label)
        if not is_open:
            continue
        word = re.compile(r"(?<![A-Za-z0-9_])([A-Z][A-Z0-9_]{3})(?![A-Za-z0-9_])")
        in_title = set(word.findall(t.get("title", "")))
        if draft:
            in_title |= {w.upper() for w in re.findall(r"[a-z0-9_]{4}", os.path.basename(path)[:-5])}
        for w in (in_title | set(word.findall(t.get("brief", "")))) & sigs:
            mentioned.setdefault(w, []).append(label)
        for w in in_title & sigs:
            titled.setdefault(w, []).append(label)
    return owned, open_owned, mentioned, titled


