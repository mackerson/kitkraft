def plan_inventory(rows, defs, xr, owned, mentioned, names):
    undefined = [r for s, r in rows.items() if r["schema"] == "-" and s not in defs]
    skipped, todo = [], []
    for r in sorted(undefined, key=lambda r: (-r["records"], r["sig"])):
        s = r["sig"]
        if s in owned or s in mentioned:
            skipped.append((s, "covered by " + ", ".join(sorted(set(owned.get(s, []) + mentioned.get(s, []))))))
        elif s not in xr:
            skipped.append((s, f"the pinned xEdit file does not define it ({comma(r['records'])} records)"))
        else:
            name = camel(xr[s]["name"])
            if name in names:
                name += "Form" if name + "Form" not in names else "Record"
            names.add(name)
            todo.append(dict(r, xedit=xr[s], name=name))
    batches, cur = [], []
    for r in todo:
        cap = BIG_BATCH if (cur[0] if cur else r)["records"] >= BIG else SMALL_BATCH
        if cur and (len(cur) >= cap or sum(c["seen"] for c in cur) + r["seen"] > MAX_SEEN
                    or (cur[0]["records"] >= BIG) != (r["records"] >= BIG)):
            batches.append(cur)
            cur = []
        cur.append(r)
    if cur:
        batches.append(cur)
    return len(undefined), batches, skipped


def plan_depth(rows, outside, defs, xr, open_owned, mentioned):
    skipped, todo = [], []
    for s, d in sorted(defs.items()):
        r = rows.get(s)
        if r is None:
            skipped.append((s, "no corpus records in docs/record-parity.md"))
            continue
        if r["schema"] == "-":
            skipped.append((s, "docs/record-parity.md is stale for it (defined, row says `-`); "
                               "rerun `cargo xtask parity`"))
            continue
        left = r["opaque"] + r["unknown"]
        if left < DEPTH_MIN:
            continue
        if s in open_owned or s in mentioned:
            skipped.append((s, "covered by " + ", ".join(sorted(set(open_owned.get(s, []) + mentioned.get(s, []))))))
        elif s in HARD:
            skipped.append((s, "hard: " + HARD[s]))
        elif s not in xr:
            skipped.append((s, "the pinned xEdit file does not define it"))
        else:
            c = dict(r, xedit=xr[s], outside=outside.get(s, []))
            c["def"] = d
            f = feasible(c)
            if f < FEASIBLE_MIN:
                raw = d["raw"]
                skipped.append((s, f"only {f} signature(s) a transcription can type"
                                   + (f": {r['unknown']} unknown inside base form component blocks (kept raw, "
                                      "docs/gaps.md)" if r["unknown"] else "")
                                   + (f"; {r['opaque']} opaque" + (f", of which {' '.join(raw)} kept raw on purpose"
                                                                   if raw else "") if r["opaque"] else "")))
                continue
            todo.append(c)
    todo.sort(key=lambda c: (-feasible(c), -c["records"], c["sig"]))
    groups, small = [], []
    for c in todo:
        if feasible(c) <= PAIR_MAX:
            small.append(c)
        else:
            groups.append([c])
    for i in range(0, len(small), 2):
        groups.append(small[i:i + 2])
    return groups, skipped


def free_ids(start, count, used):
    out, n = [], start
    while len(out) < count:
        tid = f"KK-{n:03d}"
        if tid not in used:
            out.append(tid)
        n += 1
        if n > 999:
            sys.exit("no free ticket IDs left below KK-999")
    return out


def readme_rows(new):
    text = open(README, encoding="utf-8").read()
    lines = text.split("\n")
    have = set(re.findall(r"^\| \[(KK-\d+)\]", text, re.M))
    num = lambda tid: int(tid[3:])
    added = 0
    for t in sorted(new, key=lambda t: num(t["id"])):
        if t["id"] in have:
            continue
        rows = [(i, re.match(r"^\| \[(KK-\d+)\]", l)) for i, l in enumerate(lines)]
        rows = [(i, m.group(1)) for i, m in rows if m]
        # After the last row with a lower ID (the table is in ID order), else after the last row.
        before = [i for i, tid in rows if num(tid) < num(t["id"])]
        at = (before[-1] if before else rows[-1][0]) + 1
        lines.insert(at, f"| [{t['id']}]({t['id']}.toml) | {t['title']} | generated by plan/tickets/generate.py "
                         f"{t['mode']} | " + ("held" if t.get("hold") else "queued") + " |")
        added += 1
    open(README, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    return added


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("mode", choices=["inventory", "depth"])
    ap.add_argument("--dry-run", action="store_true", help="print the tickets, write nothing")
    ap.add_argument("--limit", type=int, default=0, help="at most N tickets")
    ap.add_argument("--xedit", help="wbDefinitionsSF1.pas or the folder holding it")
    ap.add_argument("--quiet", action="store_true", help="with --dry-run: the summary only")
    a = ap.parse_args(argv)

    rows, defs, xr = parity_rows(), definitions(), xedit_records(xedit_path(a.xedit))
    tickets, merged = load_tickets(), merged_ids()
    owned, open_owned, mentioned, titled = coverage(tickets, merged, set(rows) | set(defs))
    used = {os.path.basename(p)[:-5] for p, _, d in tickets if not d}

    if a.mode == "inventory":
        n_undefined, groups, skipped = plan_inventory(rows, defs, xr, owned, mentioned, type_names())
    else:
        groups, skipped = plan_depth(rows, parity_outside(), defs, xr, open_owned, titled)
    if a.limit:
        groups = groups[:a.limit]
    ids = free_ids(START[a.mode], len(groups), used)
    n_xmiss = sum(1 for _, why in skipped if "does not define" in why)
    new = [inventory_ticket(tid, g, n_undefined, n_xmiss) if a.mode == "inventory" else depth_ticket(tid, g, families())
           for tid, g in zip(ids, groups)]

    for t in new:
        path = os.path.join(TICKETS, t["id"] + ".toml")
        if a.dry_run:
            if not a.quiet:
                print(f"----- {os.path.relpath(path, ROOT)}\n{render(t)}")
        else:
            open(path, "w", encoding="utf-8", newline="\n").write(render(t))
    added = 0 if a.dry_run or not new else readme_rows(new)

    verb = "would write" if a.dry_run else "wrote"
    print(f"generate.py {a.mode}: {verb} {len(new)} ticket(s)" + ("" if a.dry_run else f", {added} README row(s)"))
    for t in new:
        print(f"  {t['id']}  {' '.join(t['sigs']):<40} {t['title']}")
    if skipped:
        print(f"skipped {len(skipped)} type(s):")
        for s, why in skipped:
            print(f"  {s}  {why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
