#!/usr/bin/env python3
"""Generate schema tickets from the record-coverage gaps, with no model in the loop.

    python3 plan/tickets/generate.py inventory [--dry-run] [--limit N] [--xedit PATH]
    python3 plan/tickets/generate.py depth     [--dry-run] [--limit N] [--xedit PATH]

`inventory` (level 1): every record type the corpus shows with no definition (the "## Record
types" table of docs/record-parity.md, cross-checked against crates/schema/defs/), minus the
types an existing ticket or draft covers, most records first, batched into tickets shaped
like KK-022: about 5 types per ticket when they have 100 records or more, up to 8 smaller
ones. Types the pinned xEdit file does not define are skipped and listed.

`depth` (level 2): defined types with 5 or more opaque plus unknown subrecord signatures,
one ticket per type (two small ones together), shaped like KK-023: type the members from the
pinned xEdit file, a new ignored corpus test proves every record round-trips unchanged, and
the parity row improves by a stated amount (typed: at least half of the signatures a
transcription can type, i.e. opaque members not kept raw on purpose plus, for an lstring-only
definition, unknowns outside component bodies; unknown: no more than today). Types an open
ticket owns or names in its title, types with fewer than 3 typeable signatures, and hard cases
(component-block bodies the format cannot type yet, SCEN, the world family's REFR), are
skipped with the reason.

Tickets get real IDs from a free range (KK-100.. for inventory, KK-200.. for depth; used IDs
are skipped) and a row each in plan/tickets/README.md's queue table (source "generated by
plan/tickets/generate.py <mode>"). `--dry-run` prints them instead of writing; `--limit N`
caps the number of tickets. Rerunning is idempotent: a generated ticket owns its
`crates/schema/defs/<SIG>.toml`, so its types count as covered on the next run, and the
depth mode skips any type whose definition file an unmerged ticket owns.

Inputs: docs/record-parity.md (regenerate it with `cargo xtask parity` after merges for
fresh numbers; a type whose definition exists but whose row still says `-` is treated as
defined), crates/schema/defs/, plan/tickets/*.toml and drafts/*.toml, xtask/src/parity.rs
(families), the git log of main (merged tickets; the README table's `merged` state too,
which is all there is where git cannot read the checkout, e.g. a Windows worktree from WSL)
and the pinned xEdit file, read for facts only (a
record's definition line range and name): `--xedit`, else /opt/xedit-ref, else
<checkout>/../tools/xedit-ref.

Stdlib only; Python 3.11+ (tomllib): run it under WSL or Linux.
"""
