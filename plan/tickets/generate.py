def statement_end(lines, start, col):
    """Index of the line where the call opened at lines[start][col] closes (Pascal-aware:
    'strings', {comments}, (* comments *) and // comments are skipped)."""
    depth, i, j, state = 0, start, col, None
    while i < len(lines):
        s = lines[i]
        while j < len(s):
            c = s[j]
            if state == "str":
                if c == "'":
                    state = None
            elif state == "brace":
                if c == "}":
                    state = None
            elif state == "paren":
                if s.startswith("*)", j):
                    state, j = None, j + 1
            elif c == "'":
                state = "str"
            elif c == "{":
                state = "brace"
            elif s.startswith("(*", j):
                state, j = "paren", j + 1
            elif s.startswith("//", j):
                break
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    return i
            j += 1
        i, j = i + 1, 0
    return start


def xedit_records(path):
    """{SIG: dict(name, start, end, components, helper)} with 1-based inclusive line numbers."""
    lines = open(path, encoding="latin-1").read().split("\n")
    out = {}
    pat = re.compile(r"^\s*(wbRecord|wbRefRecord|ReferenceRecord)\(([A-Z0-9_]{4}),\s*'([^']*)'")
    for i, line in enumerate(lines):
        m = pat.match(line)
        if not m or m.group(2) in out:
            continue
        end = statement_end(lines, i, line.index("("))
        body = "\n".join(lines[i:end + 1])
        out[m.group(2)] = dict(name=m.group(3), start=i + 1, end=end + 1,
                               components="wbBaseFormComponents" in body,
                               helper=m.group(1) == "ReferenceRecord")
    return out


def camel(name):
    """xEdit's record name in our UpperCamelCase ('AVMS Data' -> AvmsData, 'FormID List' -> FormIdList)."""
    parts = re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|\d+", name)
    return "".join(p[:1].upper() + p[1:].lower() for p in parts) or "Unnamed"


