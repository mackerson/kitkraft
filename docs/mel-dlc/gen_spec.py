"""Generate docs/mel-dlc/mel-dlc.toml (brief rows B1, B2) from the current load order.

Every target's current ACBS is read with `kit inspect`, so the spec carries each record's own
flags and old level. Rerun it after a game or DLC update, then `kit build ... --plan`.

Writes one spec per DLC (`mel-dlc-<dlc>.toml`): a patch whose master list differs from the
source plugin's must remap FormIDs, which `build` refuses for records with opaque subrecords
that could hold FormIDs (NPC_ NAM5 and others), so each DLC's records go in their own plugin.

usage: python -I docs/mel-dlc/gen_spec.py [--profile <MO2 profile dir>] [--kit <kit.exe>]
"""
import argparse
import json
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
AUTOCALC, PCMULT, STATS_TEMPLATE = 16, 128, 2
MULT = "EE02"  # 750 thousandths, little-endian: MEL's multiplier

# (brief row, EditorID pattern). The DLC's numbered enemy tiers; see brief.md "Rows".
FAMILIES = [
    ("B1", r"SFTER_EncTerran(Human_(Grunt|Officer)|Robot_(Scout|Soldier|Devastator))\d+(Template)?"),
    ("B1", r"SFTER_EncTurretBallistic\d+(Template)?"),
    ("B1", r"SFBGS001_EncVortex(Horror|HorrorSmall|Phantom|Spawn)\d+(_?Template)?"),
    ("B1", r"SFBGS001_EncVaruun(Redeemed\d+(Template)?|00|Turret01)"),
    ("B2", r"Enc_SFBGS003_BountyTargetNPC_(City|NonCity)\d+(_?TEMPLATE)?"),
]
DLC = ("ShatteredSpace.esm", "SFBGS050.esm", "SFBGS003.esm", "SFBGS00D.esm")
# spec / plugin stem per DLC plugin that holds targets
STEMS = {"ShatteredSpace.esm": "shattered-space", "SFBGS050.esm": "terran-armada",
         "SFBGS003.esm": "trackers-alliance"}


def kit(args, exe):
    p = subprocess.run([exe, "--json", *args], capture_output=True, text=True, encoding="utf-8")
    env, _ = json.JSONDecoder().raw_decode(p.stdout)
    if "error" in env:
        sys.exit(f"kit {' '.join(args)}: {env['error']['message']}")
    return env.get("data", env)


def winners(exe, profile):
    rows, cursor = [], None
    while True:
        args = ["query", "NPC_", "--profile", profile, "--limit", "1000"]
        d = kit(args + (["--cursor", cursor] if cursor else []), exe)
        rows += d["results"]
        cursor = d.get("next_cursor")
        if not cursor:
            return rows


def acbs(form, exe, profile):
    d = kit(["inspect", form, "--profile", profile, "--max-bytes", "16"], exe)
    for s in d["versions"][-1]["subrecords"]:
        if s["signature"] == "ACBS":
            raw = bytes.fromhex(s["payload_hex"])
            return {"flags": s["value"]["Flags"], "level": int.from_bytes(raw[6:8], "little"),
                    "tflags": s["value"]["TemplateFlags"], "winner": d["versions"][-1]["plugin"]}
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", default=r"C:\Modding\MO2-Starfield\profiles\Kitkraft Dev")
    ap.add_argument("--kit", default=str(HERE.parent.parent / "bin" / "kit.exe"))
    a = ap.parse_args()

    pats = [(row, re.compile(p)) for row, p in FAMILIES]
    targets = []
    for r in winners(a.kit, a.profile):
        if not r["form"].startswith(DLC):
            continue
        row = next((row for row, p in pats if p.fullmatch(r["editor_id"] or "")), None)
        if row:
            targets.append((row, r["form"], r["editor_id"]))
    targets.sort(key=lambda t: (t[0], t[2]))

    with ThreadPoolExecutor(6) as ex:
        facts = list(ex.map(lambda t: acbs(t[1], a.kit, a.profile), targets))

    # `build` refuses to copy a record whose winning version is in a small or medium plugin
    # (FormIDs address masters by scale class; no scale-aware remap yet, lane D).
    scaled = {p["name"] for p in kit(["load", "--profile", a.profile], a.kit)["plugins"]
              if p["scale"] != "full"}

    sets, skipped = [], []
    for (row, form, eid), f in zip(targets, facts):
        if f and f["winner"] in scaled:
            skipped.append((form, eid, f"winner {f['winner']} is a scaled plugin; build cannot copy it yet"))
            continue
        if f is None or f["tflags"] & STATS_TEMPLATE or f["flags"] & PCMULT:
            skipped.append((form, eid, "level from a template" if f and f["tflags"] & STATS_TEMPLATE
                            else "already scales with the player" if f else "no ACBS"))
            continue
        sets.append((row, form, eid, f))

    for dlc, stem in STEMS.items():
        mine = [x for x in sets if x[3]["winner"] == dlc]
        skip = [x for x in skipped if x[0].startswith(dlc)]
        if not mine and not skip:
            continue
        out = [
            f"# MEL DLC extension, build 1 (levels only), {dlc}: docs/mel-dlc/brief.md rows B1, B2.",
            "# GENERATED by docs/mel-dlc/gen_spec.py from the load order below; do not edit by hand.",
            "# Each record gets MEL's rule: Flags |= AutoCalcStats|PcLevelMult, Level (multiplier) = 750,",
            "# CalcMinLevel = its old fixed level, CalcMaxLevel = 0.",
            f"# {len(mine)} records; skipped {len(skip)}:",
            *[f"#   {form} {eid}: {why}" for form, eid, why in skip],
            "",
            "version = 2",
            "strict = true",
            "",
            "[plugin]",
            "localized = false",
            'style = "kit"',
            "",
            "[load_order]",
            f"profile = '{a.profile}'",
        ]
        for row, form, eid, f in mine:
            flags = f["flags"] | AUTOCALC | PCMULT
            out += [
                "",
                "[[set]]",
                f'form = "{form}"  # {eid}, level {f["level"]}',
                f'brief = "{row}"',
                f'fields = {{ "ACBS.Flags" = {flags}, "ACBS.Level" = "hex:{MULT}", '
                f'"ACBS.CalcMinLevel" = {f["level"]}, "ACBS.CalcMaxLevel" = 0 }}',
            ]
        path = HERE / f"mel-dlc-{stem}.toml"
        path.write_text("\n".join(out) + "\n", encoding="utf-8")
        print(f"{dlc}: {len(mine)} records, {len(skip)} skipped -> {path}")


main()
