//! `cargo xtask add-def <SIG>... [--no-parity]`: registers inventory definitions
//! (`crates/schema/defs/<SIG>.toml`, written by `cargo xtask inventory-def` or by hand)
//! in every shared list a new one needs, then regenerates what depends on them.
//!
//! 1. `BUILTIN_DEFINITIONS` (`crates/schema/src/lib.rs`): the region between its
//!    `BEGIN`/`END` markers is rewritten from the directory (sorted as the list keeps it),
//!    then the file is formatted with rustfmt.
//! 2. `TYPES` in `crates/esm/tests/inventory_types.rs`, one `b"SIG",` per line, sorted.
//! 3. `BX2_INVENTORY` (the file cites xEdit) or `INVENTORY_CORPUS_ONLY` (it does not) in
//!    `crates/schema/tests/defs.rs`.
//! 4. `WITHOUT_EDID` in `crates/esm/src/bridge.rs` when the definition has no `EDID`
//!    member (the corpus gives the type none), removed from it when it has one.
//! 5. `cargo xtask codegen`, the golden seed (`KITKRAFT_UPDATE_GOLDEN=1 cargo test -p
//!    kitkraft-schema --test codegen`) and `cargo xtask parity` (needs `KITKRAFT_DATA_DIR`;
//!    `--no-parity` skips it). Codegen and parity run in this process from the on-disk
//!    definitions, since this binary embedded `BUILTIN_DEFINITIONS` before step 1.
//!
//! Idempotent: a second run changes nothing. The lists are read leniently (git conflict
//! marker lines are dropped and both sides' entries kept), so a merger runs it after two
//! schema branches conflict on those files, with the signatures of both sides.

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
use std::process::Command;

use anyhow::{bail, Context, Result};

use crate::codegen::{definition_names, rustfmt, DefSet, DEFS_DIR};

const LIB_RS: &str = "crates/schema/src/lib.rs";
const TYPES_RS: &str = "crates/esm/tests/inventory_types.rs";
const DEFS_RS: &str = "crates/schema/tests/defs.rs";
const BRIDGE_RS: &str = "crates/esm/src/bridge.rs";
const BEGIN: &str = "    // BEGIN generated by cargo xtask codegen: BUILTIN_DEFINITIONS\n";
const END: &str = "    // END generated by cargo xtask codegen: BUILTIN_DEFINITIONS\n";

/// What `add-def` needs to know of one definition file.
struct DefFacts {
    has_edid: bool,
    cites_xedit: bool,
}

fn facts(root: &Path, sig: &str) -> Result<DefFacts> {
    let path = root.join(DEFS_DIR).join(format!("{sig}.toml"));
    let text = fs::read_to_string(&path).with_context(|| {
        format!(
            "reading {} (write it first: cargo xtask inventory-def {sig} --name <TypeName>)",
            path.display()
        )
    })?;
    let table: toml::Table =
        toml::from_str(&text).with_context(|| format!("parsing {}", path.display()))?;
    let source = table
        .get("source")
        .and_then(toml::Value::as_str)
        .unwrap_or("");
    if !source.starts_with("corpus: inventory_types_full") {
        bail!(
            "{}: not an inventory definition (its source does not cite inventory_types_full)",
            path.display()
        );
    }
    let has_edid = table
        .get("member")
        .and_then(toml::Value::as_array)
        .into_iter()
        .flatten()
        .any(|m| m.get("sig").and_then(toml::Value::as_str) == Some("EDID"));
    let cites_xedit = text
        .lines()
        .filter(|l| !l.trim_start().starts_with('#'))
        .any(|l| l.contains("\"xedit: "));
    Ok(DefFacts {
        has_edid,
        cites_xedit,
    })
}

/// A git conflict marker line.
fn conflict_marker(line: &str) -> bool {
    ["<<<<<<<", "=======", ">>>>>>>", "|||||||"]
        .iter()
        .any(|m| line.starts_with(m))
}

/// The four-character signature quoted on an entry line (`b"SIG",` or `"SIG",`).
fn entry_sig(line: &str) -> Option<String> {
    let t = line.trim();
    let t = t.strip_prefix('b').unwrap_or(t);
    let inner = t.strip_prefix('"')?.strip_suffix("\",")?;
    (inner.len() == 4).then(|| inner.to_string())
}

/// Rewrites the one-entry-per-line list that opens with the line `decl` (trimmed) and
/// closes with `];` (indented as `decl`): its entries, plus `add`, minus `remove`, sorted,
/// each written as `prefix` + `"SIG",` at `indent`.
fn edit_list(
    text: &str,
    file: &str,
    decl: &str,
    prefix: &str,
    add: &BTreeSet<String>,
    remove: &BTreeSet<String>,
) -> Result<String> {
    let lines: Vec<&str> = text.split_inclusive('\n').collect();
    let start = lines
        .iter()
        .position(|l| l.trim() == decl)
        .with_context(|| format!("{file}: no line `{decl}`"))?;
    let indent: String = lines
        .get(start)
        .map(|l| l.chars().take_while(|c| *c == ' ').collect())
        .unwrap_or_default();
    let body_start = start.saturating_add(1);
    let len = lines
        .iter()
        .skip(body_start)
        .position(|l| l.trim() == "];")
        .with_context(|| format!("{file}: `{decl}` has no closing `];`"))?;
    let end = body_start.saturating_add(len);
    let mut entries: BTreeSet<String> = BTreeSet::new();
    for line in lines.get(body_start..end).unwrap_or_default() {
        let t = line.trim();
        if t.is_empty() || conflict_marker(t) {
            continue;
        }
        let sig = entry_sig(t).with_context(|| {
            format!("{file}: `{t}` in `{decl}` is not one `\"SIG\",` entry per line")
        })?;
        entries.insert(sig);
    }
    entries.extend(add.iter().cloned());
    for r in remove {
        entries.remove(r);
    }
    let mut out = String::new();
    for l in lines.get(..body_start).unwrap_or_default() {
        out.push_str(l);
    }
    for e in &entries {
        out.push_str(&format!("{indent}    {prefix}\"{e}\",\n"));
    }
    for l in lines.get(end..).unwrap_or_default() {
        out.push_str(l);
    }
    Ok(out)
}

/// `lib.rs` with the `BUILTIN_DEFINITIONS` region rewritten from `names`, formatted.
fn builtin_region(root: &Path, text: &str, names: &[String]) -> Result<String> {
    let start = text
        .find(BEGIN)
        .with_context(|| format!("{LIB_RS}: no BEGIN marker"))?
        .saturating_add(BEGIN.len());
    let stop = text
        .find(END)
        .with_context(|| format!("{LIB_RS}: no END marker"))?;
    let (Some(head), Some(tail)) = (text.get(..start), text.get(stop..)) else {
        bail!("{LIB_RS}: END marker before BEGIN");
    };
    let mut out = head.to_string();
    for n in names {
        out.push_str(&format!("    (\"{n}\", include_str!(\"../defs/{n}\")),\n"));
    }
    out.push_str(tail);
    rustfmt(root, &out)
}

/// Writes `text` to `rel` when it differs; reports what changed.
fn update(root: &Path, rel: &str, before: &str, text: &str) -> Result<bool> {
    if before == text {
        return Ok(false);
    }
    let path = root.join(rel);
    fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
    println!("add-def: updated {rel}");
    Ok(true)
}

fn read(root: &Path, rel: &str) -> Result<String> {
    let path = root.join(rel);
    let text = fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    Ok(crate::codegen::lf(&text))
}

/// `cargo xtask add-def <SIG>... [--no-parity]`.
pub(crate) fn run(root: &Path, args: &[String]) -> Result<()> {
    let mut sigs: BTreeSet<String> = BTreeSet::new();
    let mut parity = true;
    for a in args {
        match a.as_str() {
            "--no-parity" => parity = false,
            s if s.len() == 4 && !s.starts_with('-') => {
                sigs.insert(s.to_string());
            }
            other => bail!("add-def: unexpected argument `{other}`; usage: cargo xtask add-def <SIG>... [--no-parity]"),
        }
    }
    if sigs.is_empty() {
        bail!("usage: cargo xtask add-def <SIG>... [--no-parity]");
    }
    let mut xedit = BTreeSet::new();
    let mut corpus_only = BTreeSet::new();
    let mut with_edid = BTreeSet::new();
    let mut without_edid = BTreeSet::new();
    for sig in &sigs {
        let f = facts(root, sig)?;
        if f.cites_xedit {
            xedit.insert(sig.clone());
        } else {
            corpus_only.insert(sig.clone());
        }
        if f.has_edid {
            with_edid.insert(sig.clone());
        } else {
            without_edid.insert(sig.clone());
        }
    }

    let lib = read(root, LIB_RS)?;
    let names = definition_names(root)?;
    update(root, LIB_RS, &lib, &builtin_region(root, &lib, &names)?)?;

    let types = read(root, TYPES_RS)?;
    let new = edit_list(
        &types,
        TYPES_RS,
        "const TYPES: &[&[u8; 4]] = &[",
        "b",
        &sigs,
        &BTreeSet::new(),
    )?;
    update(root, TYPES_RS, &types, &new)?;

    let defs = read(root, DEFS_RS)?;
    let new = edit_list(
        &defs,
        DEFS_RS,
        "const BX2_INVENTORY: &[&str] = &[",
        "",
        &xedit,
        &corpus_only,
    )?;
    let new = edit_list(
        &new,
        DEFS_RS,
        "const INVENTORY_CORPUS_ONLY: &[&str] = &[",
        "",
        &corpus_only,
        &xedit,
    )?;
    update(root, DEFS_RS, &defs, &new)?;

    let bridge = read(root, BRIDGE_RS)?;
    let new = edit_list(
        &bridge,
        BRIDGE_RS,
        "const WITHOUT_EDID: &[&[u8; 4]] = &[",
        "b",
        &without_edid,
        &with_edid,
    )?;
    update(root, BRIDGE_RS, &bridge, &new)?;

    let set = DefSet::on_disk(root)?;
    crate::codegen::run_with(root, false, &set)?;
    golden(root)?;
    if parity {
        crate::parity::run_with(root, false, &set).context(
            "parity (set KITKRAFT_DATA_DIR, or pass --no-parity and run `cargo xtask parity` later)",
        )?;
    } else {
        println!(
            "add-def: parity skipped (--no-parity); run `cargo xtask parity` before committing"
        );
    }
    println!(
        "add-def: {} registered; next: the inventory test, `cargo xtask inventory-check {}`",
        sigs.iter().cloned().collect::<Vec<_>>().join(", "),
        sigs.iter().cloned().collect::<Vec<_>>().join(" ")
    );
    Ok(())
}

/// The golden seed, rewritten by the schema's codegen test (`crates/schema/tests/codegen.rs`).
fn golden(root: &Path) -> Result<()> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    println!("add-def: KITKRAFT_UPDATE_GOLDEN=1 cargo test -p kitkraft-schema --test codegen");
    let status = Command::new(&cargo)
        .args([
            "test",
            "--quiet",
            "-p",
            "kitkraft-schema",
            "--test",
            "codegen",
        ])
        .env("KITKRAFT_UPDATE_GOLDEN", "1")
        .current_dir(root)
        .status()
        .with_context(|| format!("could not start `{cargo}`"))?;
    if !status.success() {
        bail!("updating the golden seed failed ({status})");
    }
    Ok(())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    fn set(items: &[&str]) -> BTreeSet<String> {
        items.iter().map(|s| (*s).to_string()).collect()
    }

    #[test]
    fn lists_are_sorted_merged_and_idempotent() {
        let text = "x\n#[rustfmt::skip]\nconst TYPES: &[&[u8; 4]] = &[\n    b\"LAYR\",\n<<<<<<< HEAD\n    b\"CURV\",\n=======\n    b\"AVMD\",\n>>>>>>> other\n];\ny\n";
        let once = edit_list(
            text,
            "f",
            "const TYPES: &[&[u8; 4]] = &[",
            "b",
            &set(&["REGN"]),
            &set(&[]),
        )
        .unwrap();
        assert_eq!(
            once,
            "x\n#[rustfmt::skip]\nconst TYPES: &[&[u8; 4]] = &[\n    b\"AVMD\",\n    b\"CURV\",\n    b\"LAYR\",\n    b\"REGN\",\n];\ny\n"
        );
        let twice = edit_list(
            &once,
            "f",
            "const TYPES: &[&[u8; 4]] = &[",
            "b",
            &set(&["REGN"]),
            &set(&[]),
        )
        .unwrap();
        assert_eq!(once, twice);
        let removed = edit_list(
            &once,
            "f",
            "const TYPES: &[&[u8; 4]] = &[",
            "b",
            &set(&[]),
            &set(&["CURV"]),
        )
        .unwrap();
        assert!(!removed.contains("CURV"));
    }

    #[test]
    fn nested_lists_keep_their_indent() {
        let text = "    const WITHOUT_EDID: &[&[u8; 4]] = &[\n        b\"TES4\",\n    ];\n";
        let out = edit_list(
            text,
            "f",
            "const WITHOUT_EDID: &[&[u8; 4]] = &[",
            "b",
            &set(&["NAVI"]),
            &set(&[]),
        )
        .unwrap();
        assert_eq!(
            out,
            "    const WITHOUT_EDID: &[&[u8; 4]] = &[\n        b\"NAVI\",\n        b\"TES4\",\n    ];\n"
        );
    }

    #[test]
    fn a_stray_line_is_refused() {
        let text = "const TYPES: &[&[u8; 4]] = &[\n    b\"LAYR\", b\"CURV\",\n];\n";
        assert!(edit_list(
            text,
            "f",
            "const TYPES: &[&[u8; 4]] = &[",
            "b",
            &set(&[]),
            &set(&[])
        )
        .is_err());
    }

    /// The region holds every definition once, and rewriting it again changes nothing.
    #[test]
    fn the_builtin_region_is_stable() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        let lib = read(root, LIB_RS).unwrap();
        let names = definition_names(root).unwrap();
        let once = builtin_region(root, &lib, &names).unwrap();
        assert_eq!(builtin_region(root, &once, &names).unwrap(), once);
        for n in &names {
            assert_eq!(once.matches(&format!("\"{n}\"")).count(), 1, "{n}");
        }
    }
}
