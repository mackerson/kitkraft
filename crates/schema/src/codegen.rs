//! Rust source generation from a validated [`Schema`] (ADR 0003, M1.10).
//!
//! [`generate`] returns one self-contained Rust module as a `String`: a fixed prelude
//! (reader, `Field` trait, subrecord matcher) followed by each shared definition once,
//! one struct per header, and one typed struct per record, group, struct payload, enum and
//! flags field, in signature order, then the `Record` dispatch enum. The output depends
//! only on `std`, contains no indexing, `unwrap` or `panic`, and is rustfmt-clean, so it
//! can be checked in under the workspace lints (`examples/generated.rs` proves it on the
//! goldens). Writing it into `crates/esm` is the job of `cargo xtask codegen` (M1.15), not
//! of this crate.
//!
//! Generated records decode a record body leniently: every subrecord ends up either in a
//! typed member (as `Sub<T>`, which keeps the subrecord's `XXXX` flag) or in `extra` with
//! its original index, and `encode` puts the `extra` entries back at those indexes, so
//! `encode(decode(x)) == x` for every input, `XXXX` flags included.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::model::{
    ArrayCount, Cardinality, CommonBody, FieldDef, FieldType, HeaderDef, Member, NamedValue,
    RecordDef, Schema, Signature, SubrecordDef, UnionVariant,
};
use crate::names::{const_ident, field_ident, signature_type_name};

const PRELUDE: &str = include_str!("prelude.rs.in");

/// Code generation failed.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum CodegenError {
    /// Two definitions would produce the same Rust type name.
    #[error("generated type name {0} is produced twice; rename a member or group")]
    DuplicateType(String),
    /// A name cannot be used as a Rust identifier.
    #[error("{0:?} cannot be used as a Rust type or variant name")]
    BadIdentifier(String),
    /// A definition would produce a type name the prelude already defines.
    #[error("generated type name {0} is reserved by the generated prelude")]
    Reserved(String),
}

/// Type names defined by the prelude (and the `Record` dispatch enum); a definition that
/// would generate one of these is rejected.
pub const RESERVED_TYPE_NAMES: &[&str] = &[
    "BString",
    "ByPrefix",
    "Bytes",
    "Card",
    "Ctx",
    "DecodeError",
    "Empty",
    "Field",
    "FormId",
    "FormIds",
    "FormIdsMut",
    "Hit",
    "LString",
    "LStrings",
    "LStringsMut",
    "MemberDesc",
    "OwnedSub",
    "RawSub",
    "Reader",
    "Record",
    "Self",
    "Sig",
    "Sub",
    "Visit",
    "WString",
    "ZString",
];

/// Generates Rust source for every definition in `schema`: the prelude, then shared
/// definitions (each once), headers, records, and the signature dispatch:
/// `pub enum Record { Tes4(Tes4Record), .. }` with
/// `Record::decode(signature, subs, ctx) -> Option<Record>`, `Record::encode` and
/// `Record::signature`, plus `RECORDS: &[(Sig, &[MemberDesc])]` for matchers and
/// coverage. A schema without records gets no dispatch part.
pub fn generate(schema: &Schema) -> Result<String, CodegenError> {
    let mut g = Gen::default();
    g.out
        .push_str("// @generated by kitcraft-schema codegen. Do not edit by hand.\n");
    g.out.push_str("// Definitions:\n");
    for common in schema.common() {
        let p = &common.provenance;
        let _ = writeln!(
            g.out,
            "// - common {} ({}; {})",
            common.name, p.source, p.confidence
        );
    }
    for header in schema.headers() {
        let p = &header.provenance;
        let _ = writeln!(
            g.out,
            "// - header {} ({}; {})",
            header.name, p.source, p.confidence
        );
    }
    for record in schema.records() {
        let p = &record.provenance;
        let _ = writeln!(
            g.out,
            "// - {} ({}; {})",
            record.signature, p.source, p.confidence
        );
    }
    g.out.push('\n');
    g.out.push_str(PRELUDE);
    for common in schema.common() {
        match &common.body {
            CommonBody::Group(members) => g.shared_group(&common.name, members)?,
            CommonBody::Type(ty) => {
                g.shared_type(&common.name, ty)?;
            }
        }
    }
    for header in schema.headers() {
        g.header(header)?;
    }
    let records: Vec<&RecordDef> = schema.records().collect();
    for record in &records {
        g.record(record)?;
    }
    g.dispatch(&records)?;
    Ok(g.out)
}

#[derive(Default)]
struct Gen {
    out: String,
    types: BTreeSet<String>,
    /// Shared definitions already emitted: name -> Rust type.
    shared: BTreeMap<String, String>,
}

/// rustfmt's `struct_lit_width` under the default heuristics for `max_width = 100`.
const STRUCT_LIT_WIDTH: usize = 18;

/// A field-name string literal for error messages (`"TES4.HEDR.Version"`).
fn lit(text: &str) -> String {
    format!("{text:?}")
}

/// A signature as a byte-string literal (`*b"EDID"`).
fn sig_lit(sig: Signature) -> String {
    format!("*b{:?}", sig.as_str())
}

fn hex(value: i128) -> String {
    if value < 0 {
        value.to_string()
    } else {
        format!("{value:#x}")
    }
}

fn card_desc(card: Cardinality) -> &'static str {
    match card {
        Cardinality::Required => "Card::Required",
        Cardinality::Optional => "Card::Optional",
        Cardinality::Repeated => "Card::Repeated",
    }
}

impl Gen {
    fn claim(&mut self, name: &str) -> Result<(), CodegenError> {
        if name.is_empty() {
            return Err(CodegenError::BadIdentifier(name.to_owned()));
        }
        if RESERVED_TYPE_NAMES.contains(&name) {
            return Err(CodegenError::Reserved(name.to_owned()));
        }
        if !self.types.insert(name.to_owned()) {
            return Err(CodegenError::DuplicateType(name.to_owned()));
        }
        Ok(())
    }

    // -----------------------------------------------------------------------------------
    // Payload types.

    /// Returns the Rust type for `ty`, generating named types under `type_name` when the
    /// type needs one (structs, enums, flags).
    fn payload_type(
        &mut self,
        ty: &FieldType,
        type_name: &str,
        path: &str,
    ) -> Result<String, CodegenError> {
        Ok(match ty {
            FieldType::Scalar(s) => s.as_str().to_owned(),
            FieldType::FormId { .. } => "FormId".to_owned(),
            FieldType::Sig => "Sig".to_owned(),
            FieldType::ZString => "ZString".to_owned(),
            FieldType::LString => "LString".to_owned(),
            FieldType::WString => "WString".to_owned(),
            FieldType::BString => "BString".to_owned(),
            FieldType::Ref { name, ty } => self.shared_type(name, ty)?,
            FieldType::Empty => "Empty".to_owned(),
            FieldType::Opaque { size: Some(n) } => format!("[u8; {n}]"),
            FieldType::Opaque { size: None } => "Bytes".to_owned(),
            FieldType::Array { element, count } => {
                let element = self.payload_type(element, type_name, path)?;
                match count {
                    ArrayCount::Fixed(n) => format!("[{element}; {n}]"),
                    _ => format!("Vec<{element}>"),
                }
            }
            FieldType::Enum { base, values } => {
                self.enum_type(type_name, base.as_str(), values)?;
                type_name.to_owned()
            }
            FieldType::Flags { base, bits } => {
                self.flags_type(type_name, base.as_str(), bits)?;
                type_name.to_owned()
            }
            FieldType::Struct { fields } => {
                self.struct_type(type_name, fields, path)?;
                type_name.to_owned()
            }
            FieldType::Union { variants, .. } => {
                self.union_type(type_name, variants, path)?;
                type_name.to_owned()
            }
        })
    }

    /// An enum with one variant per layout, read through `ByPrefix` (the decider) rather
    /// than `Field::read`, which cannot see the record's EditorID.
    fn union_type(
        &mut self,
        name: &str,
        variants: &[UnionVariant],
        path: &str,
    ) -> Result<(), CodegenError> {
        self.claim(name)?;
        let mut decls = String::new();
        let mut prefixes = String::new();
        let mut reads = String::new();
        let mut writes = String::new();
        let mut visits: [String; 4] = Default::default();
        let wants = [Want::FormId, Want::FormId, Want::LString, Want::LString];
        let methods = [
            ("visit_form_ids", "&'a self", "FormIds"),
            ("visit_form_ids_mut", "&'a mut self", "FormIdsMut"),
            ("visit_lstrings", "&'a self", "LStrings"),
            ("visit_lstrings_mut", "&'a mut self", "LStringsMut"),
        ];
        for v in variants {
            if v.name == "Self" {
                return Err(CodegenError::BadIdentifier(v.name.clone()));
            }
            let inner = self.payload_type(&v.ty, &format!("{name}{}", v.name), path)?;
            let when = char::from(v.when);
            let _ = writeln!(
                decls,
                "    /// EditorID starting with `{when}`.\n    {}({inner}),",
                v.name
            );
            let _ = writeln!(prefixes, "            Self::{}(_) => b'{when}',", v.name);
            let _ = writeln!(
                reads,
                "            b'{when}' => Field::read(r, field, ctx).map(Self::{}),",
                v.name
            );
            let _ = writeln!(
                writes,
                "            Self::{}(value) => value.write(out),",
                v.name
            );
            for ((body, want), (method, _, _)) in visits.iter_mut().zip(wants).zip(methods) {
                if type_has(&v.ty, want) {
                    let _ = writeln!(
                        body,
                        "        if let Self::{}(value) = self {{\n            {method}(value, path, out);\n        }}",
                        v.name
                    );
                }
            }
        }
        let _ = write!(
            self.out,
            "
/// A payload whose layout the record's EditorID prefix selects (union). A payload no
/// variant claims is kept raw in the record's `extra`.
#[derive(Debug, Clone, PartialEq)]
pub enum {name} {{
{decls}}}

impl {name} {{
    /// The EditorID prefix byte that selects this variant.
    pub fn prefix(&self) -> u8 {{
        match self {{
{prefixes}        }}
    }}
}}

impl ByPrefix for {name} {{
    fn read_for(
        prefix: u8,
        r: &mut Reader<'_>,
        field: &'static str,
        ctx: Ctx,
    ) -> Result<Self, DecodeError> {{
        match prefix {{
{reads}            _ => Err(DecodeError::Undecided {{ field }}),
        }}
    }}
}}

impl Field for {name} {{
    /// Unions are read with [`ByPrefix::read_for`]; without the decider there is no layout.
    fn read(_r: &mut Reader<'_>, field: &'static str, _ctx: Ctx) -> Result<Self, DecodeError> {{
        Err(DecodeError::Undecided {{ field }})
    }}

    fn write(&self, out: &mut Vec<u8>) {{
        match self {{
{writes}        }}
    }}
}}
"
        );
        let mut bodies = Vec::new();
        for (body, (method, receiver, alias)) in visits.iter().zip(methods) {
            if body.is_empty() {
                continue;
            }
            bodies.push(format!(
                "    fn {method}<'a>({receiver}, path: &'static str, out: &mut {alias}<'a>) {{\n{body}    }}\n"
            ));
        }
        if bodies.is_empty() {
            let _ = writeln!(self.out, "\nimpl Visit for {name} {{}}");
        } else {
            let _ = writeln!(
                self.out,
                "\nimpl Visit for {name} {{\n{}}}",
                bodies.join("\n")
            );
        }
        Ok(())
    }

    fn enum_type(
        &mut self,
        name: &str,
        base: &str,
        values: &[NamedValue],
    ) -> Result<(), CodegenError> {
        self.claim(name)?;
        let mut variants = String::new();
        let mut from = String::new();
        let mut to = String::new();
        for v in values {
            if v.name == "Self" {
                return Err(CodegenError::BadIdentifier(v.name.clone()));
            }
            let _ = writeln!(variants, "    {},", v.name);
            let _ = writeln!(from, "            {} => Self::{},", v.value, v.name);
            let _ = writeln!(to, "            Self::{} => {},", v.name, v.value);
        }
        let _ = write!(
            self.out,
            "
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum {name} {{
{variants}    /// A value the definition does not name.
    Other({base}),
}}

impl {name} {{
    /// The variant for a stored value.
    pub fn from_raw(raw: {base}) -> Self {{
        match raw {{
{from}            other => Self::Other(other),
        }}
    }}

    /// The stored value.
    pub fn to_raw(self) -> {base} {{
        match self {{
{to}            Self::Other(raw) => raw,
        }}
    }}
}}

impl Field for {name} {{
    fn read(r: &mut Reader<'_>, field: &'static str, ctx: Ctx) -> Result<Self, DecodeError> {{
        {base}::read(r, field, ctx).map(Self::from_raw)
    }}

    fn write(&self, out: &mut Vec<u8>) {{
        self.to_raw().write(out);
    }}
}}

impl Visit for {name} {{}}
"
        );
        Ok(())
    }

    fn flags_type(
        &mut self,
        name: &str,
        base: &str,
        bits: &[NamedValue],
    ) -> Result<(), CodegenError> {
        self.claim(name)?;
        let mut consts = String::new();
        for b in bits {
            let _ = writeln!(
                consts,
                "    pub const {}: {base} = {};",
                const_ident(&b.name),
                hex(b.value)
            );
        }
        let _ = write!(
            self.out,
            "
/// Bit flags; bits without a name are preserved.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct {name}(pub {base});

impl {name} {{
{consts}
    /// Whether every bit of `mask` is set.
    pub fn contains(self, mask: {base}) -> bool {{
        self.0 & mask == mask
    }}
}}

impl Field for {name} {{
    fn read(r: &mut Reader<'_>, field: &'static str, ctx: Ctx) -> Result<Self, DecodeError> {{
        {base}::read(r, field, ctx).map(Self)
    }}

    fn write(&self, out: &mut Vec<u8>) {{
        self.0.write(out);
    }}
}}

impl Visit for {name} {{}}
"
        );
        Ok(())
    }

    fn struct_type(
        &mut self,
        name: &str,
        fields: &[FieldDef],
        path: &str,
    ) -> Result<(), CodegenError> {
        self.claim(name)?;
        let mut decls = String::new();
        let mut reads = String::new();
        let mut inits = Vec::with_capacity(fields.len());
        let mut writes = String::new();
        let mut calls = VisitCalls::default();
        for (i, f) in fields.iter().enumerate() {
            let ident = field_ident(&f.name);
            let field_path = format!("{path}.{}", f.name);
            let p = lit(&field_path);
            calls.add_type(&format!("self.{ident}"), &p, &f.ty);
            let inner = self.payload_type(&f.ty, &format!("{name}{}", f.name), &field_path)?;
            // Each field is read into a local `f<i>` in order, so a later field can use an
            // earlier one (an array's `count_from`).
            let (setup, read) = match &f.ty {
                FieldType::Array {
                    count: ArrayCount::From(source),
                    ..
                } => {
                    let j = fields
                        .iter()
                        .position(|s| s.name == *source)
                        .ok_or_else(|| CodegenError::BadIdentifier(source.clone()))?;
                    (
                        Some((
                            format!("let n{i} = "),
                            "count".to_owned(),
                            vec![format!("f{j}"), p.clone(), "r.position()".to_owned()],
                        )),
                        (
                            "read_array".to_owned(),
                            vec!["r".to_owned(), format!("n{i}"), p.clone(), "ctx".to_owned()],
                        ),
                    )
                }
                FieldType::Scalar(s) => (
                    None,
                    (
                        format!("{}::read", s.as_str()),
                        vec!["r".to_owned(), p.clone(), "ctx".to_owned()],
                    ),
                ),
                _ => (
                    None,
                    (
                        "Field::read".to_owned(),
                        vec!["r".to_owned(), p.clone(), "ctx".to_owned()],
                    ),
                ),
            };
            let setup_at = |indent: usize| {
                setup
                    .as_ref()
                    .map(|(lead, func, args)| let_call(indent, lead, func, args))
            };
            let read_inline = format!("{}({})?", read.0, read.1.join(", "));
            let mut conditions = Vec::new();
            if f.since.is_some() || f.until.is_some() {
                conditions.push(format!(
                    "ctx.has({}, {})",
                    opt_lit(f.since),
                    opt_lit(f.until)
                ));
                let _ = writeln!(decls, "    /// Present for form versions {}.", range(f));
            }
            if f.if_remaining {
                conditions.push("!r.is_empty()".to_owned());
                let _ = writeln!(
                    decls,
                    "    /// Present only when bytes remain in the payload."
                );
            }
            if conditions.is_empty() {
                let _ = writeln!(decls, "    pub {ident}: {inner},");
                if let Some(setup) = setup_at(8) {
                    reads.push_str(&setup);
                }
                reads.push_str(&let_call(8, &format!("let f{i} = "), &read.0, &read.1));
                let _ = writeln!(writes, "        self.{ident}.write(out);");
            } else {
                let _ = writeln!(decls, "    pub {ident}: Option<{inner}>,");
                let _ = writeln!(
                    reads,
                    "        let f{i} = if {} {{",
                    conditions.join(" && ")
                );
                if let Some(setup) = setup_at(12) {
                    reads.push_str(&setup);
                }
                let _ = writeln!(
                    reads,
                    "            Some({read_inline})\n        }} else {{\n            None\n        }};"
                );
                let _ = writeln!(
                    writes,
                    "        if let Some(value) = &self.{ident} {{\n            value.write(out);\n        }}"
                );
            }
            inits.push(format!("{ident}: f{i}"));
        }
        // rustfmt keeps a struct literal on one line while its body fits
        // `struct_lit_width` (18 with the default heuristics).
        let body = inits.join(", ");
        let construct = if body.len() <= STRUCT_LIT_WIDTH {
            format!("        Ok(Self {{ {body} }})\n")
        } else {
            let mut lines = String::from("        Ok(Self {\n");
            for init in &inits {
                let _ = writeln!(lines, "            {init},");
            }
            lines.push_str("        })\n");
            lines
        };
        let _ = write!(
            self.out,
            "
#[derive(Debug, Clone, PartialEq)]
pub struct {name} {{
{decls}}}

impl Field for {name} {{
    fn read(r: &mut Reader<'_>, _field: &'static str, ctx: Ctx) -> Result<Self, DecodeError> {{
{reads}{construct}    }}

    fn write(&self, out: &mut Vec<u8>) {{
{writes}    }}
}}
"
        );
        self.out.push_str(&visit_impl(name, &calls));
        Ok(())
    }

    /// The Rust type of a whole subrecord payload. Arrays get a newtype so they can
    /// implement `Field`.
    fn subrecord_type(
        &mut self,
        sub: &SubrecordDef,
        type_name: &str,
        path: &str,
    ) -> Result<String, CodegenError> {
        let FieldType::Array { element, count } = &sub.ty else {
            return self.payload_type(&sub.ty, type_name, path);
        };
        self.claim(type_name)?;
        let mut calls = VisitCalls::default();
        calls.add_type("self.0", "path", element);
        let element = self.payload_type(element, &format!("{type_name}Item"), path)?;
        let inner = match count {
            ArrayCount::Fixed(n) => format!("[{element}; {n}]"),
            _ => format!("Vec<{element}>"),
        };
        let _ = write!(
            self.out,
            "
#[derive(Debug, Clone, PartialEq)]
pub struct {type_name}(pub {inner});

impl Field for {type_name} {{
    fn read(r: &mut Reader<'_>, field: &'static str, ctx: Ctx) -> Result<Self, DecodeError> {{
        Field::read(r, field, ctx).map(Self)
    }}

    fn write(&self, out: &mut Vec<u8>) {{
        self.0.write(out);
    }}
}}
"
        );
        self.out.push_str(&visit_impl(type_name, &calls));
        Ok(type_name.to_owned())
    }

    // -----------------------------------------------------------------------------------
    // Headers, records and groups.

    /// A shared group, emitted once under its own name.
    fn shared_group(&mut self, name: &str, members: &[Member]) -> Result<(), CodegenError> {
        if self.shared.contains_key(name) {
            return Ok(());
        }
        self.shared.insert(name.to_owned(), name.to_owned());
        self.member_set(name, name, members, name, false)?;
        Ok(())
    }

    /// A shared type, emitted once; returns its Rust type (the shared name for structs,
    /// enums and flags, the plain type otherwise).
    fn shared_type(&mut self, name: &str, ty: &FieldType) -> Result<String, CodegenError> {
        if let Some(rust) = self.shared.get(name) {
            return Ok(rust.clone());
        }
        let rust = self.payload_type(ty, name, name)?;
        self.shared.insert(name.to_owned(), rust.clone());
        Ok(rust)
    }

    /// The `Record` enum, its `decode`/`encode`/`signature`, and `RECORDS`.
    fn dispatch(&mut self, records: &[&RecordDef]) -> Result<(), CodegenError> {
        if records.is_empty() {
            return Ok(());
        }
        let mut variants = String::new();
        let mut table = String::new();
        let mut decodes = String::new();
        let mut encodes = String::new();
        let mut sigs = String::new();
        let mut forwards: [String; 5] = Default::default();
        let forward_names = [
            "form_ids",
            "form_ids_mut",
            "lstrings",
            "lstrings_mut",
            "extra",
        ];
        for rec in records {
            let variant = signature_type_name(rec.signature.as_str());
            for (body, method) in forwards.iter_mut().zip(forward_names) {
                let call = if method == "extra" {
                    "&record.extra".to_owned()
                } else {
                    format!("record.{method}()")
                };
                let _ = writeln!(body, "            Self::{variant}(record) => {call},");
            }
        }
        let [f0, f1, f2, f3, f4] = &forwards;
        for rec in records {
            let variant = signature_type_name(rec.signature.as_str());
            let ty = format!("{variant}Record");
            let _ = writeln!(variants, "    {variant}(Box<{ty}>),");
            let _ = writeln!(table, "    ({}, {ty}::MEMBERS),", sig_lit(rec.signature));
            let _ = writeln!(
                decodes,
                "            b{:?} => Self::{variant}(Box::new({ty}::decode(subs, ctx))),",
                rec.signature.as_str()
            );
            let _ = writeln!(
                encodes,
                "            Self::{variant}(record) => record.encode(),"
            );
            let _ = writeln!(sigs, "            Self::{variant}(_) => {ty}::SIGNATURE,");
        }
        let _ = write!(
            self.out,
            "
/// A decoded record of any type the schema defines (boxed: record structs are large).
#[derive(Debug, Clone, PartialEq)]
pub enum Record {{
{variants}}}

/// The member list of every defined record type, by signature.
pub const RECORDS: &[(Sig, &[MemberDesc])] = &[
{table}];

impl Record {{
    /// Decodes a record body of type `signature`; `None` when the schema has no
    /// definition for it (the container keeps such records raw).
    pub fn decode(signature: Sig, subs: &[RawSub<'_>], ctx: Ctx) -> Option<Self> {{
        Some(match &signature {{
{decodes}            _ => return None,
        }})
    }}

    /// Encodes the record body.
    pub fn encode(&self) -> Vec<OwnedSub> {{
        match self {{
{encodes}        }}
    }}

    /// The record signature.
    pub fn signature(&self) -> Sig {{
        match self {{
{sigs}        }}
    }}

    /// Every FormID-typed value with its path (see each record's `form_ids`).
    pub fn form_ids(&self) -> FormIds<'_> {{
        match self {{
{f0}        }}
    }}

    /// Every FormID-typed value with its path, mutably.
    pub fn form_ids_mut(&mut self) -> FormIdsMut<'_> {{
        match self {{
{f1}        }}
    }}

    /// Every lstring value with its path (see each record's `lstrings`).
    pub fn lstrings(&self) -> LStrings<'_> {{
        match self {{
{f2}        }}
    }}

    /// Every lstring value with its path, mutably.
    pub fn lstrings_mut(&mut self) -> LStringsMut<'_> {{
        match self {{
{f3}        }}
    }}

    /// Subrecords the definition did not place or could not decode, with their indexes
    /// in the body as read (empty when every subrecord decoded into a typed member).
    pub fn extra(&self) -> &[(usize, OwnedSub)] {{
        match self {{
{f4}        }}
    }}
}}
"
        );
        Ok(())
    }

    fn header(&mut self, h: &HeaderDef) -> Result<(), CodegenError> {
        let name = h.name.clone();
        let path = match h.signature {
            Some(sig) => sig.as_str().to_owned(),
            None => h.name.clone(),
        };
        self.struct_type(&name, &h.fields, &path)?;
        let _ = write!(
            self.out,
            "
impl {name} {{
    /// Header size in bytes.
    pub const SIZE: usize = {size};

    /// Decodes a header; `data` must be exactly [`Self::SIZE`] bytes.
    pub fn decode(data: &[u8]) -> Result<Self, DecodeError> {{
        decode(data, {path}, Ctx::default())
    }}
}}
",
            size = h.size,
            path = lit(&path),
        );
        Ok(())
    }

    fn record(&mut self, rec: &RecordDef) -> Result<(), CodegenError> {
        let prefix = signature_type_name(rec.signature.as_str());
        let name = format!("{prefix}Record");
        self.member_set(&name, &prefix, &rec.members, rec.signature.as_str(), true)?;
        let mut flags = String::new();
        for f in &rec.flags {
            let _ = writeln!(
                flags,
                "    /// Record-header flag.\n    pub const FLAG_{}: u32 = {};",
                const_ident(&f.name),
                hex(f.value)
            );
        }
        let _ = write!(
            self.out,
            "
impl {name} {{
    /// Record signature.
    pub const SIGNATURE: Sig = {sig};
{flags}
    /// Decodes a record body. Never fails: subrecords that match no member or do not
    /// decode are kept in `extra`.
    pub fn decode(subs: &[RawSub<'_>], ctx: Ctx) -> Self {{
        let (hits, unmatched_indexes) = match_members(subs, Self::MEMBERS);
        let mut record = Self::default();
        let mut extra = Vec::new();
        for index in unmatched_indexes {{
            if let Some(sub) = subs.get(index) {{
                extra.push((index, OwnedSub::from(sub)));
            }}
        }}
        record.fill(&hits, subs, ctx, &mut extra);
        record.extra = extra;
        record
    }}

    /// Encodes the record body: typed members in definition order, `extra` re-inserted at
    /// the indexes it was read from.
    pub fn encode(&self) -> Vec<OwnedSub> {{
        let mut out = Vec::new();
        self.emit(&mut out);
        merge_extra(out, &self.extra)
    }}

    /// Every FormID-typed value (raw, as stored), in definition order, with the path of
    /// the member or field holding it. `extra` and opaque payloads are not visited.
    pub fn form_ids(&self) -> FormIds<'_> {{
        let mut out = Vec::new();
        self.visit_form_ids({path}, &mut out);
        out
    }}

    /// [`Self::form_ids`], mutably (for remapping FormIDs in place).
    pub fn form_ids_mut(&mut self) -> FormIdsMut<'_> {{
        let mut out = Vec::new();
        self.visit_form_ids_mut({path}, &mut out);
        out
    }}

    /// Every lstring value, in definition order, with the path of the member or field
    /// holding it. `extra` and opaque payloads are not visited.
    pub fn lstrings(&self) -> LStrings<'_> {{
        let mut out = Vec::new();
        self.visit_lstrings({path}, &mut out);
        out
    }}

    /// [`Self::lstrings`], mutably (for replacing string IDs with inline text).
    pub fn lstrings_mut(&mut self) -> LStringsMut<'_> {{
        let mut out = Vec::new();
        self.visit_lstrings_mut({path}, &mut out);
        out
    }}
}}
",
            sig = sig_lit(rec.signature),
            path = lit(rec.signature.as_str()),
        );
        Ok(())
    }

    /// Generates the struct for a record or group: one field per member plus `fill`,
    /// `emit` and `MEMBERS`. Returns the struct name.
    fn member_set(
        &mut self,
        name: &str,
        prefix: &str,
        members: &[Member],
        path: &str,
        is_record: bool,
    ) -> Result<String, CodegenError> {
        let mut decls = String::new();
        let mut descs = String::new();
        let mut arms = String::new();
        let mut emits = String::new();
        let mut uses_ctx = false;
        let mut calls = VisitCalls::default();
        for (index, member) in members.iter().enumerate() {
            let ident = field_ident(member.name());
            match member {
                Member::Subrecord(sub) => {
                    uses_ctx = true;
                    let sub_path = format!("{path}.{}", sub.signature);
                    calls.add_type(&format!("self.{ident}"), &lit(&sub_path), &sub.ty);
                    let ty =
                        self.subrecord_type(sub, &format!("{prefix}{}", sub.name), &sub_path)?;
                    let sig = sig_lit(sub.signature);
                    let is_union = matches!(sub.ty, FieldType::Union { .. });
                    let (push_fn, put_fn) = if is_union {
                        ("push_by_prefix", "put_by_prefix")
                    } else {
                        ("push", "put")
                    };
                    let _ = writeln!(
                        decls,
                        "    /// `{}`, {}.",
                        sub.signature,
                        sub.cardinality.as_str()
                    );
                    let _ = writeln!(
                        descs,
                        "        MemberDesc::Sub {{\n            sig: {sig},\n            card: {},\n        }},",
                        card_desc(sub.cardinality)
                    );
                    if sub.cardinality == Cardinality::Repeated {
                        let _ = writeln!(decls, "    pub {ident}: Vec<Sub<{ty}>>,");
                        arms.push_str(&call_arm(
                            &format!("Hit::Sub {{ member: {index}, index }}"),
                            push_fn,
                            &[
                                &format!("&mut self.{ident}"),
                                "subs",
                                "*index",
                                &lit(&sub_path),
                                "ctx",
                                "extra",
                            ],
                        ));
                        let _ = writeln!(
                            emits,
                            "        for value in &self.{ident} {{\n            emit(out, {sig}, Some(value));\n        }}"
                        );
                    } else {
                        let _ = writeln!(decls, "    pub {ident}: Option<Sub<{ty}>>,");
                        arms.push_str(&call_arm(
                            &format!("Hit::Sub {{ member: {index}, index }}"),
                            put_fn,
                            &[
                                &format!("&mut self.{ident}"),
                                "subs",
                                "*index",
                                &lit(&sub_path),
                                "ctx",
                                "extra",
                            ],
                        ));
                        emits.push_str(&call_stmt(
                            8,
                            "emit",
                            &[
                                "out".to_owned(),
                                sig.clone(),
                                format!("self.{ident}.as_ref()"),
                            ],
                        ));
                    }
                }
                Member::Group(group) => {
                    uses_ctx = true;
                    calls.add_members(
                        &format!("self.{ident}"),
                        &lit(&format!("{path}.{}", group.name)),
                        &group.members,
                    );
                    let group_name = match &group.shared {
                        Some(shared) => {
                            self.shared_group(shared, &group.members)?;
                            shared.clone()
                        }
                        None => {
                            let group_name = format!("{prefix}{}", group.name);
                            let group_path = format!("{path}.{}", group.name);
                            self.member_set(
                                &group_name,
                                &group_name,
                                &group.members,
                                &group_path,
                                false,
                            )?;
                            group_name
                        }
                    };
                    let _ = writeln!(
                        decls,
                        "    /// Group `{}`, {}.",
                        group.name,
                        group.cardinality.as_str()
                    );
                    let _ = writeln!(
                        descs,
                        "        MemberDesc::Group {{\n            card: {},\n            members: {group_name}::MEMBERS,\n        }},",
                        card_desc(group.cardinality)
                    );
                    if group.cardinality == Cardinality::Repeated {
                        let _ = writeln!(decls, "    pub {ident}: Vec<{group_name}>,");
                        let _ = writeln!(
                            arms,
                            "                Hit::Group {{ member: {index}, hits }} => {{\n                    let mut group = {group_name}::default();\n                    group.fill(hits, subs, ctx, extra);\n                    self.{ident}.push(group);\n                }}"
                        );
                        let _ = writeln!(
                            emits,
                            "        for group in &self.{ident} {{\n            group.emit(out);\n        }}"
                        );
                    } else {
                        let _ = writeln!(decls, "    pub {ident}: Option<{group_name}>,");
                        let _ = writeln!(
                            arms,
                            "                Hit::Group {{ member: {index}, hits }} if self.{ident}.is_none() => {{\n                    let mut group = {group_name}::default();\n                    group.fill(hits, subs, ctx, extra);\n                    self.{ident} = Some(group);\n                }}"
                        );
                        let _ = writeln!(
                            emits,
                            "        if let Some(group) = &self.{ident} {{\n            group.emit(out);\n        }}"
                        );
                    }
                }
                Member::AnyUntil(any) => {
                    let _ = writeln!(
                        decls,
                        "    /// Raw subrecords up to `{}`, in order.",
                        any.until
                    );
                    let _ = writeln!(decls, "    pub {ident}: Vec<OwnedSub>,");
                    let _ = writeln!(
                        descs,
                        "        MemberDesc::AnyUntil {{ until: {} }},",
                        sig_lit(any.until)
                    );
                    arms.push_str(&call_arm(
                        &format!("Hit::Sub {{ member: {index}, index }}"),
                        "push_raw",
                        &[&format!("&mut self.{ident}"), "subs", "*index"],
                    ));
                    let _ = writeln!(emits, "        out.extend(self.{ident}.iter().cloned());");
                }
            }
        }
        self.claim(name)?;
        if is_record {
            decls.push_str(
                "    /// Subrecords that matched no member or failed to decode, each with its index\n    /// in the record body as read. `encode` re-inserts them at those indexes (see\n    /// `merge_extra`); when typed values are added or removed, an index stays a number,\n    /// so the entry may land next to different neighbours.\n    pub extra: Vec<(usize, OwnedSub)>,\n",
            );
        }
        let ctx = if uses_ctx { "ctx" } else { "_ctx" };
        let fill_body = if members.is_empty() {
            "        for hit in hits {\n            unmatched(hit, subs, extra);\n        }\n"
                .to_owned()
        } else {
            format!(
                "        for hit in hits {{\n            match hit {{\n{arms}                _ => unmatched(hit, subs, extra),\n            }}\n        }}\n"
            )
        };
        let emit_fn = if members.is_empty() {
            "    fn emit(&self, _out: &mut Vec<OwnedSub>) {}\n".to_owned()
        } else {
            format!("    fn emit(&self, out: &mut Vec<OwnedSub>) {{\n{emits}    }}\n")
        };
        let members_list = if descs.is_empty() {
            "&[]".to_owned()
        } else {
            format!(
                "&[
{descs}    ]"
            )
        };
        let _ = write!(
            self.out,
            "
#[derive(Debug, Clone, PartialEq, Default)]
pub struct {name} {{
{decls}}}

impl {name} {{
    /// Members in on-disk order.
    pub const MEMBERS: &'static [MemberDesc] = {members_list};

    fn fill(
        &mut self,
        hits: &[Hit],
        subs: &[RawSub<'_>],
        {ctx}: Ctx,
        extra: &mut Vec<(usize, OwnedSub)>,
    ) {{
{fill_body}    }}

{emit_fn}}}
"
        );
        self.out.push_str(&visit_impl(name, &calls));
        Ok(name.to_owned())
    }
}

/// Width limits of rustfmt's default heuristics for `max_width = 100` (`fn_call_width`
/// bounds the argument list).
const MAX_WIDTH: usize = 100;
const FN_CALL_WIDTH: usize = 60;
/// Indentation of match arms inside `fill`.
const ARM_INDENT: usize = 16;

/// A `{lead}{func}(args)?;` statement at `indent`, laid out the way rustfmt lays it out:
/// on one line when it fits, otherwise one argument per line.
fn let_call(indent: usize, lead: &str, func: &str, args: &[String]) -> String {
    let joined = args.join(", ");
    let pad = " ".repeat(indent);
    let line = format!("{pad}{lead}{func}({joined})?;");
    if joined.len() <= FN_CALL_WIDTH && line.len() <= MAX_WIDTH {
        return format!("{line}\n");
    }
    let mut out = format!("{pad}{lead}{func}(\n");
    for arg in args {
        let _ = writeln!(out, "{pad}    {arg},");
    }
    let _ = writeln!(out, "{pad})?;");
    out
}

/// A `func(args);` statement at `indent`, laid out like [`let_call`].
fn call_stmt(indent: usize, func: &str, args: &[String]) -> String {
    let joined = args.join(", ");
    let pad = " ".repeat(indent);
    let line = format!("{pad}{func}({joined});");
    if joined.len() <= FN_CALL_WIDTH && line.len() <= MAX_WIDTH {
        return format!("{line}\n");
    }
    let mut out = format!("{pad}{func}(\n");
    for arg in args {
        let _ = writeln!(out, "{pad}    {arg},");
    }
    let _ = writeln!(out, "{pad});");
    out
}

/// One `pattern => func(args),` match arm, laid out the way rustfmt lays it out: on one
/// line when it fits, one argument per line when the call itself is too wide, otherwise
/// the call in a block on its own line.
fn call_arm(pattern: &str, func: &str, args: &[&str]) -> String {
    let joined = args.join(", ");
    let call = format!("{func}({joined})");
    let pad = " ".repeat(ARM_INDENT);
    let one_line = ARM_INDENT
        .saturating_add(pattern.len())
        .saturating_add(" => ".len())
        .saturating_add(call.len())
        .saturating_add(",".len());
    if joined.len() <= FN_CALL_WIDTH && one_line <= MAX_WIDTH {
        return format!("{pad}{pattern} => {call},\n");
    }
    if joined.len() > FN_CALL_WIDTH {
        let mut out = format!("{pad}{pattern} => {func}(\n");
        for arg in args {
            let _ = writeln!(out, "{pad}    {arg},");
        }
        let _ = writeln!(out, "{pad}),");
        return out;
    }
    format!("{pad}{pattern} => {{\n{pad}    {call}\n{pad}}}\n")
}

/// What a visitor collects.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Want {
    FormId,
    LString,
}

/// Whether a value of `ty` holds a `formid` (or `lstring`) anywhere inside.
fn type_has(ty: &FieldType, want: Want) -> bool {
    match ty {
        FieldType::FormId { .. } => want == Want::FormId,
        FieldType::LString => want == Want::LString,
        FieldType::Array { element, .. } => type_has(element, want),
        FieldType::Struct { fields } => fields.iter().any(|f| type_has(&f.ty, want)),
        FieldType::Ref { ty, .. } => type_has(ty, want),
        FieldType::Union { variants, .. } => variants.iter().any(|v| type_has(&v.ty, want)),
        _ => false,
    }
}

/// Whether any member in `members` (groups included) holds a `formid` (or `lstring`).
fn members_have(members: &[Member], want: Want) -> bool {
    members.iter().any(|m| match m {
        Member::Subrecord(s) => type_has(&s.ty, want),
        Member::Group(g) => members_have(&g.members, want),
        Member::AnyUntil(_) => false,
    })
}

/// The calls a type's `Visit` impl makes: `(receiver, path expression)` per visitor.
#[derive(Default)]
struct VisitCalls {
    form_ids: Vec<(String, String)>,
    lstrings: Vec<(String, String)>,
}

impl VisitCalls {
    /// Adds `receiver` (a field of `self`) with `path` for each visitor `ty` needs.
    fn add_type(&mut self, receiver: &str, path: &str, ty: &FieldType) {
        if type_has(ty, Want::FormId) {
            self.form_ids.push((receiver.to_owned(), path.to_owned()));
        }
        if type_has(ty, Want::LString) {
            self.lstrings.push((receiver.to_owned(), path.to_owned()));
        }
    }

    /// Adds a group member.
    fn add_members(&mut self, receiver: &str, path: &str, members: &[Member]) {
        if members_have(members, Want::FormId) {
            self.form_ids.push((receiver.to_owned(), path.to_owned()));
        }
        if members_have(members, Want::LString) {
            self.lstrings.push((receiver.to_owned(), path.to_owned()));
        }
    }
}

/// One visitor method: name, receiver, list alias, and the calls it makes.
type VisitMethod<'c> = (
    &'static str,
    &'static str,
    &'static str,
    &'c [(String, String)],
);

/// The `impl Visit for {name}` block: only the visitors with something to visit are
/// written; the others keep the trait's empty defaults.
fn visit_impl(name: &str, calls: &VisitCalls) -> String {
    let methods: [VisitMethod<'_>; 4] = [
        ("visit_form_ids", "&'a self", "FormIds", &calls.form_ids),
        (
            "visit_form_ids_mut",
            "&'a mut self",
            "FormIdsMut",
            &calls.form_ids,
        ),
        ("visit_lstrings", "&'a self", "LStrings", &calls.lstrings),
        (
            "visit_lstrings_mut",
            "&'a mut self",
            "LStringsMut",
            &calls.lstrings,
        ),
    ];
    let mut bodies = Vec::new();
    for (method, receiver, alias, list) in methods {
        if list.is_empty() {
            continue;
        }
        let borrow = if receiver.contains("mut") {
            "&mut "
        } else {
            "&"
        };
        let param = if list.iter().any(|(_, p)| p == "path") {
            "path"
        } else {
            "_path"
        };
        let mut body = format!(
            "    fn {method}<'a>({receiver}, {param}: &'static str, out: &mut {alias}<'a>) {{\n"
        );
        for (field, path) in list {
            body.push_str(&visit_call(method, &format!("{borrow}{field}"), path));
        }
        body.push_str("    }\n");
        bodies.push(body);
    }
    if bodies.is_empty() {
        return format!("\nimpl Visit for {name} {{}}\n");
    }
    format!("\nimpl Visit for {name} {{\n{}}}\n", bodies.join("\n"))
}

/// One `func(receiver, path, out);` statement inside a visitor body, laid out the way
/// rustfmt lays out a call: on one line when the arguments fit `fn_call_width` and the
/// line fits, otherwise one argument per line.
fn visit_call(func: &str, receiver: &str, path: &str) -> String {
    let args = [receiver, path, "out"];
    let joined = args.join(", ");
    let line = format!("        {func}({joined});");
    if joined.len() <= FN_CALL_WIDTH && line.len() <= MAX_WIDTH {
        return format!("{line}\n");
    }
    let mut out = format!("        {func}(\n");
    for arg in args {
        let _ = writeln!(out, "            {arg},");
    }
    out.push_str("        );\n");
    out
}

fn opt_lit(v: Option<u16>) -> String {
    match v {
        Some(v) => format!("Some({v})"),
        None => "None".to_owned(),
    }
}

fn range(f: &FieldDef) -> String {
    match (f.since, f.until) {
        (Some(s), Some(u)) => format!("{s}..={u}"),
        (Some(s), None) => format!("{s} and later"),
        (None, Some(u)) => format!("up to {u}"),
        (None, None) => "all".to_owned(),
    }
}
