    /// A throwaway MO2 instance: `ModOrganizer.ini`, `mods\`, `overwrite\`, a game dir and
    /// `profiles\P`.
    struct Instance {
        root: PathBuf,
    }

    impl Instance {
        fn new(tag: &str) -> Instance {
            let root =
                std::env::temp_dir().join(format!("kitkraft-io-{tag}-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&root);
            for d in ["mods", "overwrite", "profiles/P", "Game/Data"] {
                std::fs::create_dir_all(root.join(d)).unwrap();
            }
            let game = root.join("Game").to_string_lossy().replace('\\', "\\\\");
            std::fs::write(
                root.join("ModOrganizer.ini"),
                format!("[General]\r\ngameName=Starfield\r\ngamePath=@ByteArray({game})\r\n"),
            )
            .unwrap();
            Instance { root }
        }
        fn profile(&self) -> PathBuf {
            self.root.join("profiles/P")
        }
        fn write(&self, rel: &str, bytes: &[u8]) {
            let path = self.root.join(rel);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, bytes).unwrap();
        }
        fn provider(&self, load: &ProfileLoad, rel: &str) -> String {
            load.overlay
                .resolve(rel)
                .map(|r| r.provider.label())
                .unwrap_or_default()
        }
    }

    fn plan(inst: &Instance) -> ProfileLoad {
        plan_profile(&inst.profile(), &ProfileOptions::default()).unwrap()
    }

    #[test]
    fn priority_disabled_separators_missing_dirs_and_case() {
        let inst = Instance::new("prio");
        inst.write(
            "profiles/P/modlist.txt",
            b"\xEF\xBB\xBF# This file was automatically generated by Mod Organizer.\r\n+Patch\r\n+Gear_separator\r\n-Off\r\n+Ghost\r\n+Base\r\n*Unmanaged: DLC\r\n",
        );
        inst.write("mods/Base/Textures/A.dds", b"base");
        inst.write("mods/Base/textures/b.dds", b"base");
        inst.write("mods/Base/meta.ini", b"[General]");
        inst.write("mods/Patch/textures/a.DDS", b"patch");
        inst.write("mods/Off/textures/b.dds", b"off");
        inst.write("mods/Gear_separator/textures/b.dds", b"sep");
        inst.write("overwrite/Textures/C.dds", b"ow");
        inst.write("mods/Base/Textures/C.dds", b"base");
        inst.write("Game/Data/Textures/D.dds", b"data");
        let profile = Profile::read(&inst.profile()).unwrap();
        assert_eq!(
            profile
                .enabled_mods()
                .iter()
                .map(|m| m.name.as_str())
                .collect::<Vec<_>>(),
            ["Patch", "Ghost", "Base"]
        );
        let load = ProfileLoad {
            overlay: Overlay::build(&profile, Depth::Full),
            plan: LoadPlan::default(),
            profile,
        };
        // First modlist line wins; overwrite beats every mod; case and slashes ignored.
        assert_eq!(inst.provider(&load, "textures\\a.dds"), "mod:Patch");
        assert_eq!(inst.provider(&load, "TEXTURES/B.DDS"), "mod:Base");
        assert_eq!(inst.provider(&load, "textures/c.dds"), "overwrite");
        assert_eq!(inst.provider(&load, "textures/d.dds"), "data");
        assert_eq!(inst.provider(&load, "meta.ini"), "");
        assert_eq!(inst.provider(&load, "textures/none.dds"), "");
        assert_eq!(load.overlay.missing_mod_dirs, ["Ghost"]);
        let found = load.overlay.resolve("Textures/D.DDS").unwrap();
        assert!(found.path.ends_with("Textures\\D.dds") || found.path.ends_with("Textures/D.dds"));
    }

    #[test]
    fn root_overlay_resolves_deep_paths_and_lists_archives() {
        let inst = Instance::new("deep");
        inst.write("profiles/P/modlist.txt", b"+Patch\n+Base\n");
        inst.write("mods/Patch/Strings/mod_en.strings", b"p");
        inst.write("mods/Base/strings/MOD_EN.STRINGS", b"b");
        inst.write("mods/Base/Mod - Main.ba2", b"x");
        inst.write("Game/Data/Mod - Localization.ba2", b"x");
        inst.write("Game/Data/Mod - Textures.ba2", b"x");
        inst.write("Game/Data/Other - Main.ba2", b"x");
        let load = plan(&inst);
        let found = load.overlay.resolve("Strings/mod_en.strings").unwrap();
        assert_eq!(found.provider, Provider::Mod("Patch".into()));
        let names: Vec<String> = load
            .overlay
            .archives_for("Mod")
            .iter()
            .map(|p| p.file_name().unwrap().to_string_lossy().into_owned())
            .collect();
        assert_eq!(
            names,
            [
                "Mod - Localization.ba2",
                "Mod - Main.ba2",
                "Mod - Textures.ba2"
            ]
        );
    }

    #[test]
    fn active_plugins_and_order() {
        let inst = Instance::new("plugins");
        inst.write(
            "profiles/P/modlist.txt",
            b"+Mod A\n-Mod B\n*Unmanaged: DLC\n*Unmanaged: Gone\n",
        );
        inst.write(
            "profiles/P/plugins.txt",
            b"# This file is used by Starfield to keep track of your downloaded content.\r\n*A.esm\r\nB.esm\r\n*Missing.esm\r\n",
        );
        inst.write(
            "profiles/P/loadorder.txt",
            b"# gen\r\nStarfield.esm\r\nCore2.esm\r\nA.esm\r\nB.esm\r\nDLC.esm\r\nBlueprintShips-DLC.esm\r\n",
        );
        inst.write(
            "profiles/P/Starfield.ccc",
            b"Starfield.esm\r\nCore2.esm\r\n",
        );
        inst.write("profiles/P/lockedorder.txt", b"# gen\r\n");
        inst.write("Game/Data/Starfield.esm", b"x");
        inst.write("Game/Data/core2.ESM", b"x");
        inst.write("Game/Data/DLC.esm", b"x");
        inst.write("Game/Data/BlueprintShips-DLC.esm", b"x");
        inst.write("Game/Data/SFBGS050.esm", b"x");
        inst.write("mods/Mod A/A.esm", b"x");
        inst.write("mods/Mod B/B.esm", b"x");
        let load = plan(&inst);
        let rows: Vec<(String, Option<String>, bool)> = load
            .plan
            .plugins
            .iter()
            .map(|p| {
                (
                    p.name.clone(),
                    p.active.as_ref().map(Active::label),
                    p.file.is_some(),
                )
            })
            .collect();
        let row = |n: &str, a: Option<&str>, f: bool| (n.to_string(), a.map(str::to_string), f);
        assert_eq!(
            rows,
            [
                // `hardcoded-official-slots`: the official plugins first, those the game's
                // order names in that order (SFBGS050 although loadorder.txt omits it),
                // then the other ccc plugins, then other official plugins without a
                // plugins.txt entry, although loadorder.txt lists them later.
                row("Starfield.esm", Some("Starfield.ccc"), true),
                row("SFBGS050.esm", Some("hardcoded-official"), true),
                row("Core2.esm", Some("Starfield.ccc"), true),
                row("DLC.esm", Some("mo2-unmanaged:Unmanaged: DLC"), true),
                row(
                    "BlueprintShips-DLC.esm",
                    Some("blueprint-companion-of:DLC.esm"),
                    true
                ),
                row("A.esm", Some("plugins.txt"), true),
                // Listed without `*`, and its mod is disabled: inactive, no file.
                row("B.esm", None, false),
                row("Missing.esm", Some("plugins.txt"), false),
            ]
        );
        assert_eq!(
            load.plan.hardcoded_slots,
            ["SFBGS050.esm", "DLC.esm", "BlueprintShips-DLC.esm"]
        );
        assert_eq!(load.plan.moved, ["DLC.esm", "BlueprintShips-DLC.esm"]);
        assert_eq!(load.plan.missing(), ["Missing.esm"]);
        assert_eq!(load.plan.specs().len(), 6);
        assert!(load.plan.warnings.iter().any(|w| w.contains("Gone")));
        assert!(load
            .plan
            .warnings
            .iter()
            .any(|w| w.contains("SFBGS050.esm is active but not in loadorder.txt")));
        // The game's official order wins over the ccc's for the plugins it names; the ccc
        // orders the official plugins it does not name.
        inst.write(
            "profiles/P/Starfield.ccc",
            b"Core2.esm\r\nCore1.esm\r\nStarfield.esm\r\n",
        );
        inst.write("Game/Data/Core1.esm", b"x");
        let load = plan(&inst);
        let names: Vec<&str> = load.plan.plugins.iter().map(|p| p.name.as_str()).collect();
        assert_eq!(
            names[..5],
            [
                "Starfield.esm",
                "SFBGS050.esm",
                "Core2.esm",
                "Core1.esm",
                "DLC.esm"
            ]
        );
        assert!(load.profile.warnings.is_empty());
        // core2.ESM on disk resolves for Core2.esm.
        assert!(load.plan.get("core2.esm").unwrap().file.is_some());
    }

    /// The `KitKraft Dev` profile as it was for the owner's saves of 2026-10-15 (Autosave1
    /// `000039` with the POI; Exitsave0 `000052` with the gun overhaul too): its files, the
    /// plan, the inferred runtime slots and the saves' lists agree slot for slot
    /// (`docs/poi/first-poi-investigation.md`). Real plugin headers (flags as the official
    /// files carry them), so the blueprint rule reads the flag.
    #[test]
    fn kitkraft_dev_order_matches_its_saves() {
        use crate::save::tests::{bcps, save_data};
        use crate::testdata::{dev_flags, tiny_plugin, DEV_FULL, DEV_MEDIUM, DEV_SMALL};
        use kitkraft_doc::{LoadOptions, LoadOrder, RuntimeSlot};

        let inst = Instance::new("dev-saves");
        inst.write(
            "profiles/P/modlist.txt",
            b"# gen\r\n+Kitkraft POI dev\r\n+KitKraft Gun Overhaul\r\n-Tower Hab 2\r\n*Unmanaged: BlueprintShips-SFBGS050\r\n*Unmanaged: SFBGS004\r\n*Unmanaged: SFBGS00D\r\n*Unmanaged: SFBGS047\r\n*Unmanaged: SFBGS050\r\n*Unmanaged: ShatteredSpace\r\n",
        );
        inst.write(
            "profiles/P/Starfield.ccc",
            b"Starfield.esm\r\nConstellation.esm\r\nOldMars.esm\r\nBlueprintShips-Starfield.esm\r\nSFBGS007.esm\r\nSFBGS008.esm\r\nSFBGS006.esm\r\nSFBGS003.esm\r\n",
        );
        inst.write(
            "profiles/P/loadorder.txt",
            b"# gen\r\nStarfield.esm\r\nConstellation.esm\r\nOldMars.esm\r\nBlueprintShips-Starfield.esm\r\nSFBGS007.esm\r\nSFBGS008.esm\r\nSFBGS006.esm\r\nSFBGS003.esm\r\nKitKraftFirstPOI.esm\r\nKitKraftGunOverhaul.esm\r\nSFBGS004.esm\r\nSFBGS00D.esm\r\nSFBGS047.esm\r\nSFBGS050.esm\r\nBlueprintShips-SFBGS050.esm\r\nShatteredSpace.esm\r\n",
        );
        let official: Vec<&str> = DEV_FULL
            .iter()
            .chain(&DEV_SMALL)
            .chain(&DEV_MEDIUM)
            .filter(|(_, o)| *o)
            .map(|(n, _)| *n)
            .collect();
        for n in &official {
            inst.write(&format!("Game/Data/{n}"), &tiny_plugin(dev_flags(n)));
        }
        inst.write(
            "mods/Kitkraft POI dev/KitKraftFirstPOI.esm",
            &tiny_plugin(0x1),
        );
        inst.write(
            "mods/KitKraft Gun Overhaul/KitKraftGunOverhaul.esm",
            &tiny_plugin(0x1),
        );
        let check = |plugins_txt: &[u8], full: &[(&str, bool)], save: &str| {
            inst.write("profiles/P/plugins.txt", plugins_txt);
            let load = plan(&inst);
            let lo = LoadOrder::load(load.plan.specs(), &LoadOptions::default()).unwrap();
            let path = inst.root.join(save);
            std::fs::write(
                &path,
                bcps(&save_data(full, &DEV_SMALL, &DEV_MEDIUM), 0x40000),
            )
            .unwrap();
            let header = crate::save::read_save_header(&path).unwrap();
            let m = crate::save::match_load_order(&lo, &header);
            assert!(m.confirmed(), "{save}: {m:?}");
            assert_eq!(m.differs_from_inferred, Vec::<String>::new(), "{save}");
            (load, lo)
        };
        // Autosave1 000039: only the POI enabled.
        let (load, lo) = check(
            b"# gen\r\n*KitKraftFirstPOI.esm\r\nKitKraftGunOverhaul.esm\r\nSFBGS004.esm\r\nSFBGS00D.esm\r\nSFBGS047.esm\r\nSFBGS050.esm\r\nBlueprintShips-SFBGS050.esm\r\nShatteredSpace.esm\r\n",
            &DEV_FULL,
            "Autosave1.sfs",
        );
        let poi = lo.find("KitKraftFirstPOI.esm").unwrap();
        assert_eq!(
            lo.plugin(poi).unwrap().runtime_slot,
            Some(RuntimeSlot::Full(4))
        );
        assert_eq!(
            lo.runtime_id(kitkraft_doc::GlobalForm {
                plugin: poi,
                object_id: 0x1000
            }),
            Some(0x0400_1000)
        );
        // The plan: official plugins in the game's order, blueprint plugins with them (their
        // runtime slots come last), then the user's.
        let names: Vec<&str> = load
            .plan
            .plugins
            .iter()
            .filter(|p| p.active.is_some())
            .map(|p| p.name.as_str())
            .collect();
        assert_eq!(
            names,
            [
                "Starfield.esm",
                "Constellation.esm",
                "OldMars.esm",
                "BlueprintShips-Starfield.esm",
                "SFBGS004.esm",
                "SFBGS007.esm",
                "SFBGS008.esm",
                "SFBGS003.esm",
                "SFBGS006.esm",
                "ShatteredSpace.esm",
                "SFBGS00D.esm",
                "SFBGS050.esm",
                "BlueprintShips-SFBGS050.esm",
                "SFBGS047.esm",
                "KitKraftFirstPOI.esm",
            ]
        );
        assert_eq!(
            load.plan.get("ShatteredSpace.esm").unwrap().active,
            Some(Active::Hardcoded)
        );
        // Exitsave0 000052: the gun overhaul too, at 05; the blueprint plugins move to 06, 07.
        let mut full = DEV_FULL.to_vec();
        full.insert(5, ("KitKraftGunOverhaul.esm", false));
        let (_, lo) = check(
            b"# gen\r\n*KitKraftFirstPOI.esm\r\n*KitKraftGunOverhaul.esm\r\nSFBGS004.esm\r\nSFBGS00D.esm\r\nSFBGS047.esm\r\nSFBGS050.esm\r\nBlueprintShips-SFBGS050.esm\r\nShatteredSpace.esm\r\n",
            &full,
            "Exitsave0.sfs",
        );
        let gun = lo.find("KitKraftGunOverhaul.esm").unwrap();
        assert_eq!(
            lo.plugin(gun).unwrap().runtime_slot,
            Some(RuntimeSlot::Full(5))
        );
    }

    #[test]
    fn not_a_profile_and_no_game_path() {
        let inst = Instance::new("errors");
        assert!(matches!(
            Profile::read(&inst.profile()),
            Err(IoError::NotAProfile(_))
        ));
        inst.write("profiles/P/modlist.txt", b"+A\nbad line\n");
        std::fs::write(inst.root.join("ModOrganizer.ini"), b"[General]\n").unwrap();
        assert!(matches!(
            Profile::read(&inst.profile()),
            Err(IoError::Instance(_))
        ));
        let p = Profile::read_with(
            &inst.profile(),
            &ProfileOptions {
                data_dir: Some(inst.root.join("Game/Data")),
            },
        )
        .unwrap();
        assert_eq!(p.warnings.len(), 1);
        assert_eq!(p.mods.len(), 1);
    }

    #[test]
    fn explicit_plugins_resolve_against_data_dir() {
        let inst = Instance::new("explicit");
        inst.write("Game/Data/A.esm", b"x");
        let data = inst.root.join("Game/Data");
        let other = inst.root.join("B.esm");
        std::fs::write(&other, b"x").unwrap();
        let (specs, missing) = plan::explicit(
            &[
                "A.esm".into(),
                other.to_string_lossy().into_owned(),
                "C.esm".into(),
            ],
            Some(Path::new(&data)),
        );
        assert_eq!(specs.len(), 2);
        assert_eq!(specs[1].name, "B.esm");
        assert_eq!(missing.len(), 1);
    }
