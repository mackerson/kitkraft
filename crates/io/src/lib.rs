/// A profile read and planned: the profile, its overlay (plugins only) and the plan.
#[derive(Debug, Clone)]
pub struct ProfileLoad {
    /// The profile files.
    pub profile: Profile,
    /// Root-level overlay.
    pub overlay: Overlay,
    /// Plugins in order.
    pub plan: LoadPlan,
}

/// Read `profile_dir` and plan its load order.
pub fn plan_profile(
    profile_dir: &std::path::Path,
    options: &ProfileOptions,
) -> Result<ProfileLoad> {
    let profile = Profile::read_with(profile_dir, options)?;
    let overlay = Overlay::build(&profile, Depth::Root);
    let plan = LoadPlan::new(&profile, &overlay);
    Ok(ProfileLoad {
        profile,
        overlay,
        plan,
    })
}

